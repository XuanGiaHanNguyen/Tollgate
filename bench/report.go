//go:build ignore

// report regenerates docs/METRICS.md from bench/results/*.json.
//
//	go run ./bench/report.go
//
// For each experiment and mode (laptop, aws) the newest full run is shown;
// quick smoke runs are skipped. METRICS.md is never edited by hand.
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"log"
	"os"
	"sort"
	"strings"

	"github.com/XuanGiaHanNguyen/Tollgate/internal/benchfmt"
)

var experiments = []struct{ id, question string }{
	{"E1", "How fast is the gateway?"},
	{"E2", "Does bytecode beat tree-walking?"},
	{"E3", "How accurate is distributed limiting?"},
	{"E4", "Does consistent hashing minimize movement?"},
	{"E5", "How does Raft behave?"},
	{"E6", "How fast does config reach gateways?"},
	{"E7", "Does the breaker protect latency?"},
	{"E8", "Do cost budgets hold?"},
	{"E9", "Does hedging cut tail latency?"},
	{"E10", "What does the safety filter cost?"},
	{"E11", "Does safe rollout catch bad config?"},
	{"SIM", "Does Raft stay safe under seeded faults? (deterministic simulation)"},
}

func main() {
	in := flag.String("results", "bench/results", "results directory")
	out := flag.String("out", "docs/METRICS.md", "output file")
	readme := flag.String("readme", "README.md", "README whose results block (between markers) is regenerated; empty to skip")
	flag.Parse()

	all, err := benchfmt.LoadAll(*in)
	if err != nil {
		log.Fatal(err)
	}
	// newest full run per experiment and mode
	latest := map[string]*benchfmt.Result{}
	for _, r := range all {
		if q, _ := r.Params["quick"].(bool); q {
			continue
		}
		latest[r.Experiment+"/"+r.Env.Mode] = r
	}

	var b strings.Builder
	b.WriteString("# Metrics\n\n")
	b.WriteString("Generated by `go run ./bench/report.go` from `bench/results/`. Do not edit by hand.\n\n")
	b.WriteString("Each section shows the newest full run of an experiment. Laptop, CI-runner and AWS numbers are reported separately and never mixed. ")
	b.WriteString("Every load run lasts the stated measured window after a warm-up, is repeated the stated number of times, and the median run is reported.\n\n")

	for _, mode := range []string{"laptop", "ci-runner", "aws"} {
		title := map[string]string{"laptop": "Laptop", "ci-runner": "GitHub Actions runner (clean Linux VM)", "aws": "AWS"}[mode]
		fmt.Fprintf(&b, "## %s\n\n", title)
		any := false
		for _, e := range experiments {
			r := latest[e.id+"/"+mode]
			if r == nil {
				continue
			}
			any = true
			fmt.Fprintf(&b, "### %s: %s\n\n", e.id, e.question)
			writeEnv(&b, r)
			switch e.id {
			case "E1":
				writeE1(&b, r)
			case "E2":
				writeE2(&b, r)
			case "E3":
				writeE3(&b, r)
			case "E4":
				writeE4(&b, r)
			case "E5":
				writeE5(&b, r)
			case "E6":
				writeE6(&b, r)
			case "E7":
				writeE7(&b, r)
			case "E8":
				writeE8(&b, r)
			case "E9":
				writeE9(&b, r)
			case "E10":
				writeE10(&b, r)
			case "E11":
				writeE11(&b, r)
			case "SIM":
				writeSim(&b, r)
			default:
				b.WriteString("_No renderer for this experiment yet; see the raw result file._\n\n")
			}
		}
		if !any {
			b.WriteString("_No results yet._\n\n")
		}
	}

	b.WriteString("## Not yet measured\n\n")
	for _, e := range experiments {
		if latest[e.id+"/laptop"] == nil && latest[e.id+"/aws"] == nil {
			fmt.Fprintf(&b, "- %s: %s\n", e.id, e.question)
		}
	}
	if err := os.WriteFile(*out, []byte(b.String()), 0o644); err != nil {
		log.Fatal(err)
	}
	log.Printf("wrote %s", *out)
	if *readme != "" {
		if err := writeReadme(*readme, latest); err != nil {
			log.Fatal(err)
		}
	}
}

const (
	markStart = "<!-- results:start (generated by bench/report.go; do not edit) -->"
	markEnd   = "<!-- results:end -->"
)

// writeReadme regenerates the headline table between the markers.
func writeReadme(path string, latest map[string]*benchfmt.Result) error {
	b, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	s := string(b)
	i, j := strings.Index(s, markStart), strings.Index(s, markEnd)
	if i < 0 || j < i {
		return nil // no block to regenerate
	}
	var t strings.Builder
	t.WriteString(markStart + "\n\n| | Question | Laptop (Apple M2, shared) | CI runner (clean Linux VM) |\n| --- | --- | --- | --- |\n")
	for _, e := range experiments {
		lap, ci := headline(e.id, latest[e.id+"/laptop"]), headline(e.id, latest[e.id+"/ci-runner"])
		if lap == "" && ci == "" {
			continue
		}
		fmt.Fprintf(&t, "| %s | %s | %s | %s |\n", e.id, e.question, orDash(lap), orDash(ci))
	}
	t.WriteString("\nFull tables, methods and environments: [docs/METRICS.md](docs/METRICS.md).\n\n" + markEnd)
	return os.WriteFile(path, []byte(s[:i]+t.String()+s[j+len(markEnd):]), 0o644)
}

// headline is a one-line summary of a result, from its stored summary.
func headline(id string, r *benchfmt.Result) string {
	if r == nil {
		return ""
	}
	switch id {
	case "E1":
		var s e1Summary
		if json.Unmarshal(r.Summary, &s) != nil {
			return ""
		}
		var parts []string
		for _, t := range s.Targets {
			if t.Gateways > 0 {
				parts = append(parts, fmt.Sprintf("%d gw: %d req/s", t.Gateways, t.MaxSustainedRPS))
			}
		}
		return strings.Join(parts, ", ") + fmt.Sprintf(" at p99 < %.0f ms", s.P99LimitMs)
	case "E2":
		var s e2Summary
		if json.Unmarshal(r.Summary, &s) != nil || len(s.Sizes) == 0 {
			return ""
		}
		z := s.Sizes[len(s.Sizes)-1]
		return fmt.Sprintf("VM %.2f× the interpreter on %d rules; 0 allocs", z.Speedup, z.Stmts)
	case "E3":
		var s e3Summary
		if json.Unmarshal(r.Summary, &s) != nil {
			return ""
		}
		for _, m := range s.Modes {
			if m.Name == "cluster_batched" {
				run := m.Runs[m.Median]
				return fmt.Sprintf("over-admission %+.2f%% across 3 gateways (batched, %.2f RPCs/req)", run.Phases["measure"].OverAdmission, run.RPCsPerReq)
			}
		}
	case "E4":
		var s e4Summary
		if json.Unmarshal(r.Summary, &s) != nil {
			return ""
		}
		for _, row := range s.Rows {
			if row.VNodes == 128 {
				return fmt.Sprintf("%.1f%% of keys moved (ideal 25%%), %d misplaced; max/mean load %.2f", row.AddMovedPct, row.AddWrongMoves+row.RemWrongMoves, row.S3["max_over_mean"])
			}
		}
	case "E5":
		var s e5Summary
		if json.Unmarshal(r.Summary, &s) != nil || len(s.Runs) == 0 {
			return ""
		}
		m := s.Runs[s.Median]
		lost, acked := 0, 0
		var fo []float64
		for _, run := range s.Runs {
			lost += run.Lost
			acked += run.Acked
			fo = append(fo, run.Failovers...)
		}
		sort.Float64s(fo)
		med := 0.0
		if len(fo) > 0 {
			med = fo[len(fo)/2]
		}
		return fmt.Sprintf("commit p50 %.1f / p99 %.1f ms; failover p50 %.0f ms; %d of %d writes lost", m.CommitP50Ms, m.CommitP99Ms, med, lost, acked)
	case "E6":
		var s e6Summary
		if json.Unmarshal(r.Summary, &s) != nil || len(s.Runs) == 0 {
			return ""
		}
		m := s.Runs[s.Median]
		return fmt.Sprintf("config on all gateways p50 %.1f / p99 %.1f ms after commit", m.P50Ms, m.P99Ms)
	case "E7":
		var s e7Summary
		if json.Unmarshal(r.Summary, &s) != nil {
			return ""
		}
		var on, off float64
		for _, m := range s.Modes {
			e := m.Runs[m.Median].Phases["failing"].ErrorRate * 100
			if m.Name == "breaker_on" {
				on = e
			} else {
				off = e
			}
		}
		return fmt.Sprintf("client errors %.1f%% → %.1f%% with the breaker", off, on)
	case "E8":
		var s e8Summary
		if json.Unmarshal(r.Summary, &s) != nil {
			return ""
		}
		vals := map[string]float64{}
		leaked := int64(0)
		for _, m := range s.Modes {
			vals[m.Name] = m.Runs[m.Median].OverspendPct
			for _, run := range m.Runs {
				leaked += run.LeakedHolds
			}
		}
		return fmt.Sprintf("overspend %+.2f%% (reserve-and-settle) vs %+.1f%% (count limit); %d leaked holds", vals["cost_budget"], vals["request_count_limit"], leaked)
	case "E9":
		var s e9Summary
		if json.Unmarshal(r.Summary, &s) != nil {
			return ""
		}
		for _, m := range s.Modes {
			if m.MaxPct == 5 {
				return fmt.Sprintf("TTFT p99 %+.0f%% for %+.2f%% cost (5%% hedge budget)", m.P99Cut, m.ExtraPct)
			}
		}
	case "E10":
		var s e10Summary
		if json.Unmarshal(r.Summary, &s) != nil || len(s.Sizes) == 0 {
			return ""
		}
		z := s.Sizes[len(s.Sizes)-1]
		return fmt.Sprintf("%.0f MB/s with %d patterns; split-pattern recall %.0f%%", z.Runs[z.Median].MBPerSec, z.Patterns, z.RecallPct)
	case "E11":
		var s struct {
			Cases []struct {
				Scenario   string  `json:"scenario"`
				Outcome    string  `json:"outcome"`
				DecisionMs float64 `json:"commit_to_decision_ms"`
			} `json:"cases"`
		}
		if json.Unmarshal(r.Summary, &s) != nil {
			return ""
		}
		lo, hi, ok, n := 1e18, 0.0, 0, 0
		for _, c := range s.Cases {
			n++
			want := "rolled_back"
			if c.Scenario == "good" {
				want = "promoted"
			} else {
				lo, hi = min(lo, c.DecisionMs), max(hi, c.DecisionMs)
			}
			if c.Outcome == want {
				ok++
			}
		}
		return fmt.Sprintf("bad configs rolled back in %.1f–%.1f s; %d/%d decisions correct", lo/1000, hi/1000, ok, n)
	case "SIM":
		var s struct {
			Suites []map[string]int `json:"suites"`
			All    bool             `json:"all_mutants_caught"`
		}
		if json.Unmarshal(r.Summary, &s) != nil || len(s.Suites) == 0 {
			return ""
		}
		return fmt.Sprintf("%d seeds × %d suites pass; planted Raft bugs caught: %v", s.Suites[0]["seeds"], len(s.Suites), s.All)
	}
	return ""
}

func writeEnv(b *strings.Builder, r *benchfmt.Result) {
	e := r.Env
	commit := e.GitCommit
	if len(commit) > 12 {
		commit = commit[:12]
	}
	if e.GitDirty {
		commit += " (uncommitted changes)"
	}
	rows := [][2]string{
		{"Run", fmt.Sprintf("%s → %s (UTC)", r.StartedAt.Format("2006-01-02 15:04"), r.FinishedAt.Format("15:04"))},
		{"Commit", "`" + commit + "`"},
		{"Machine", fmt.Sprintf("%s, %s, %d CPUs, %.0f GB", e.Machine, e.CPU, e.CPUs, e.MemoryGB)},
		{"OS / Go / k6", fmt.Sprintf("%s / %s / %s", e.OS, e.GoVersion, orDash(e.K6Version))},
		{"Topology", fmt.Sprintf("%s; %d gateway node(s) max", e.Topology, e.NodeCount)},
		{"Load average at start", orDash(e.LoadAvg1m)},
		{"Power", orDash(e.Power)},
	}
	if _, ok := r.Params["measure_seconds"]; ok {
		rows = append(rows, [2]string{"Measured window × reps", fmt.Sprintf("%vs after %vs warm-up × %v (median reported)", r.Params["measure_seconds"], r.Params["warmup_seconds"], r.Params["reps"])})
	} else {
		rows = append(rows, [2]string{"Repetitions", fmt.Sprintf("%v (median reported)", r.Params["reps"])})
	}
	if e.Note != "" {
		rows = append(rows, [2]string{"Note", e.Note})
	}
	b.WriteString("| Environment | |\n| --- | --- |\n")
	for _, row := range rows {
		fmt.Fprintf(b, "| %s | %s |\n", row[0], row[1])
	}
	b.WriteString("\n")
}

func orDash(s string) string {
	if s == "" {
		return "—"
	}
	return s
}

