type e1Run struct {
	Latency         benchfmt.LatencyStats `json:"latency"`
	ErrorRate       float64               `json:"error_rate"`
	Dropped         float64               `json:"dropped_iterations"`
	AchievedRPS     float64               `json:"achieved_rps"`
	CPUCores        float64               `json:"gateway_cpu_cores"`
	RSSMB           float64               `json:"gateway_rss_mb"`
	OverheadP50Usec float64               `json:"gateway_overhead_p50_us"`
	OverheadP99Usec float64               `json:"gateway_overhead_p99_us"`
}

type e1Summary struct {
	P99LimitMs float64 `json:"p99_limit_ms"`
	Targets    []struct {
		Name     string `json:"name"`
		Gateways int    `json:"gateways"`
		Levels   []struct {
			Rate   int     `json:"rate"`
			Runs   []e1Run `json:"runs"`
			Median int     `json:"median_run"`
			Pass   bool    `json:"pass"`
			Reason string  `json:"reason"`
		} `json:"levels"`
		MaxSustainedRPS int `json:"max_sustained_rps"`
	} `json:"targets"`
	Overhead []struct {
		Rate     int     `json:"rate"`
		Target   string  `json:"target"`
		AddP50Ms float64 `json:"added_p50_ms"`
		AddP99Ms float64 `json:"added_p99_ms"`
	} `json:"overhead_vs_direct"`
}

var targetLabel = map[string]string{"direct": "Direct to backends (baseline)", "gw1": "1 gateway", "gw3": "3 gateways"}

func writeE1(b *strings.Builder, r *benchfmt.Result) {
	var s e1Summary
	if err := json.Unmarshal(r.Summary, &s); err != nil {
		fmt.Fprintf(b, "_Unreadable summary: %v_\n\n", err)
		return
	}
	fmt.Fprintf(b, "Method: k6 constant-arrival-rate `GET` on a rising rate ladder; a level passes when p99 < %.0f ms, errors < 0.1%% and the load generator dropped < 1%% of iterations. The ladder stops at the first failing level. 3 mock backends with no added latency.\n\n", s.P99LimitMs)

	b.WriteString("**Max sustained rate**\n\n| Target | Max sustained req/s | Gateway CPU at that rate (cores) | Gateway RSS (MB) |\n| --- | --- | --- | --- |\n")
	for _, t := range s.Targets {
		cpu, rss := "—", "—"
		for _, l := range t.Levels {
			if l.Rate == t.MaxSustainedRPS && t.Gateways > 0 {
				m := l.Runs[l.Median]
				cpu, rss = fmt.Sprintf("%.2f", m.CPUCores), fmt.Sprintf("%.0f", m.RSSMB)
			}
		}
		max := fmt.Sprintf("%d", t.MaxSustainedRPS)
		if t.MaxSustainedRPS == 0 {
			max = "none passed"
		} else if n := len(t.Levels); n > 0 && t.Levels[n-1].Pass {
			max = fmt.Sprintf("≥ %d (highest level tested; limit not reached)", t.MaxSustainedRPS)
		}
		fmt.Fprintf(b, "| %s | %s | %s | %s |\n", targetLabel[t.Name], max, cpu, rss)
	}
	b.WriteString("\n")

	if len(s.Overhead) > 0 {
		b.WriteString("**Latency added vs direct** (median runs at the same rate; includes the extra network hop)\n\n| Rate (req/s) | Target | Added p50 (ms) | Added p99 (ms) |\n| --- | --- | --- | --- |\n")
		ov := s.Overhead
		sort.SliceStable(ov, func(i, j int) bool {
			if ov[i].Target != ov[j].Target {
				return ov[i].Target < ov[j].Target
			}
			return ov[i].Rate < ov[j].Rate
		})
		for _, o := range ov {
			fmt.Fprintf(b, "| %d | %s | %.3f | %.3f |\n", o.Rate, targetLabel[o.Target], o.AddP50Ms, o.AddP99Ms)
		}
		b.WriteString("\n")
	}

	b.WriteString("Gateway overhead percentiles are estimated from the `tollgate_gateway_overhead_seconds` histogram, whose buckets double in width (…, 25, 50, 100 µs, …), so they are accurate to the bucket, not to the microsecond. Negative added latency means run-to-run noise on the shared laptop exceeded the gateway's cost at that rate.\n\n")
	b.WriteString("**All levels** (median run)\n\n| Target | Rate | p50 (ms) | p99 (ms) | Errors | Achieved req/s | GW CPU (cores) | GW overhead p50 / p99 (µs, from /metrics) | Result |\n| --- | --- | --- | --- | --- | --- | --- | --- | --- |\n")
	for _, t := range s.Targets {
		for _, l := range t.Levels {
			m := l.Runs[l.Median]
			cpu, ovh := "—", "—"
			if t.Gateways > 0 {
				cpu = fmt.Sprintf("%.2f", m.CPUCores)
				ovh = fmt.Sprintf("%.0f / %.0f", m.OverheadP50Usec, m.OverheadP99Usec)
			}
			res := "pass"
			if !l.Pass {
				res = "fail: " + l.Reason
			}
			fmt.Fprintf(b, "| %s | %d | %.3f | %.3f | %.2f%% | %.0f | %s | %s | %s |\n",
				t.Name, l.Rate, m.Latency.P50, m.Latency.P99, m.ErrorRate*100, m.AchievedRPS, cpu, ovh, res)
		}
	}
	b.WriteString("\n")
}

// ---- E7 ----

type e7Summary struct {
	Modes []struct {
		Name string `json:"name"`
		Runs []struct {
			Phases map[string]struct {
				Latency   benchfmt.LatencyStats `json:"latency"`
				ErrorRate float64               `json:"error_rate"`
			} `json:"phases"`
			FailureToOpenMs    float64 `json:"failure_to_open_ms"`
			RecoveryToClosedMs float64 `json:"recovery_to_closed_ms"`
			OpensWhileFailing  int     `json:"opens_while_failing"`
		} `json:"runs"`
		Median int `json:"median_run"`
	} `json:"modes"`
}

func writeE7(b *strings.Builder, r *benchfmt.Result) {
	var s e7Summary
	if err := json.Unmarshal(r.Summary, &s); err != nil {
		fmt.Fprintf(b, "_Unreadable summary: %v_\n\n", err)
		return
	}
	fmt.Fprintf(b, "Method: %v req/s through 1 gateway to 3 backends (%v). One backend is switched to %v errors for the failing phase and back. Breaker on vs off, otherwise identical config; passive health checks %v.\n\n",
		r.Params["rate"], r.Params["backend_latency"], r.Params["injected_error_rate"], r.Params["passive_health"])
	if bo, ok := r.Params["breaker_on"].(string); ok {
		fmt.Fprintf(b, "Breaker config (on): `%s`\n\n", strings.TrimSpace(bo))
	}

	b.WriteString("**Latency and errors by phase** (median run by failing-phase p99)\n\n| Breaker | Phase | p50 (ms) | p99 (ms) | Error rate |\n| --- | --- | --- | --- | --- |\n")
	for _, m := range s.Modes {
		run := m.Runs[m.Median]
		for _, p := range []string{"before", "failing", "recovered"} {
			ph := run.Phases[p]
			fmt.Fprintf(b, "| %s | %s | %.3f | %.3f | %.2f%% |\n", strings.TrimPrefix(m.Name, "breaker_"), p, ph.Latency.P50, ph.Latency.P99, ph.ErrorRate*100)
		}
	}
	b.WriteString("\n")

	for _, m := range s.Modes {
		if m.Name != "breaker_on" {
			continue
		}
		var opens, closes []string
		for _, run := range m.Runs {
			opens = append(opens, msOrNever(run.FailureToOpenMs))
			closes = append(closes, msOrNever(run.RecoveryToClosedMs))
		}
		run := m.Runs[m.Median]
		fmt.Fprintf(b, "**Breaker timing** (polled every %v)\n\n| | Median run | All runs |\n| --- | --- | --- |\n", r.Params["poll_resolution"])
		fmt.Fprintf(b, "| Failure → breaker open | %s | %s |\n", msOrNever(run.FailureToOpenMs), strings.Join(opens, ", "))
		fmt.Fprintf(b, "| Recovery → breaker closed | %s | %s |\n", msOrNever(run.RecoveryToClosedMs), strings.Join(closes, ", "))
		fmt.Fprintf(b, "| Times opened while failing | %d | |\n\n", run.OpensWhileFailing)
	}
}

func msOrNever(v float64) string {
	if v < 0 {
		return "never"
	}
	return fmt.Sprintf("%.0f ms", v)
}

